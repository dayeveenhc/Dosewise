// Optional curated, human-reviewed translations of a medication's simple
// instruction, keyed by language → medication name. Medication dosing text is
// safety-sensitive, so we deliberately do NOT machine-translate it: when no
// curated string exists we fall back to the (curated, English) `fallback` the
// caller passes in rather than risk a wrong auto-translation of a dose. Extend
// this table with reviewed translations to localise med directions per language.
type MedTextStyle = "simple";
const MED_TEXT_I18N: Partial<Record<AppLanguage, Record<string, string>>> = {};

export function localizeMedText(
  language: AppLanguage,
  medName: string,
  _style: MedTextStyle,
  fallback: string,
): string {
  return MED_TEXT_I18N[language]?.[medName] ?? fallback;
}
