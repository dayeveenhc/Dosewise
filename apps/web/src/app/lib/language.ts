export function t(language: AppLanguage, key: string, params?: Record<string, string | number>) {
  const value = TRANSLATIONS[language]?.[key] ?? TRANSLATIONS.en[key] ?? key;
  return Object.entries(params ?? {}).reduce((acc, [k, v]) => acc.replaceAll(`{${k}}`, String(v)), value);
}

export function getLanguageLabel(language: AppLanguage) {
  return LANGUAGE_OPTIONS.find(option => option.id === language)?.label ?? LANGUAGE_OPTIONS[0].label;
}

